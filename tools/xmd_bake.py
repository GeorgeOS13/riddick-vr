#!/usr/bin/env python3
"""Bake real Riddick ``.xmd`` meshes into a native C++ asset (GH #55 -> #46).

``tools/xmd_export.py`` already turns a ``MOS DATAFILE2.0`` ``.xmd`` into OBJ /
skin JSON for inspection. This tool closes the last gap before a native first-
person draw path: it bakes the **bind-pose** geometry of specific clusters into
a dependency-free C++ header (``src/hook/native_hand_mesh_data.h``) that the
hook can compile in directly, so no runtime file I/O or binary re-parser is
needed inside the game process.

It is strictly read-only: the game install is never written, and the emitted
header is the only artifact (plus an optional JSON manifest for evidence).

The canonical bake (``--set hands``) selects the two textured Riddick forearm
clusters from ``Riddick_B05.xmd`` (the in-game body arms, surface
``RIDDICK_ARMSCAR_*``) and both ``Pa2_Hand_01.xmd`` hand clusters:

  * ``Riddick_LeftArm``   Riddick_B05.xmd cluster 1 (526 verts, bones 10-23)
  * ``Riddick_RightArm``  Riddick_B05.xmd cluster 2 (344 verts, bones 10-23)
  * ``Pa2_Hand``          Pa2_Hand_01.xmd cluster 0 (138 verts, textured)
  * ``Pa2_Hand_Detail``   Pa2_Hand_01.xmd cluster 1 (540 verts, untextured)

Coordinate system: the engine's raw model-space floats (Z-up), unconverted.

Geometry: the baked positions are the engine's raw per-cluster model-space
floats. An earlier revision of this note claimed they *are* the ``NODES`` bind
pose, citing ``tools/xmd_fk.py --check``; that check cannot support the claim
(at the bind pose every FK world map is the identity, so the influence-weighted
blend equals the file geometry by construction for *any* input). The direct
measurement (``tools/xmd_pose.py``, ADR-0424) shows the two ``Riddick_B05`` arm
clusters are not at the ``NODES`` bind pose (raised reference pose, ~26-27 unit
same-bone offsets vs the body). ``.xmd`` stores no bone rotations (``KEYS`` is a
string metadata map, ADR-0421); the ADR-0441 recipe applies the engine's own
bind-relative world deltas to the stored geometry, so it remains faithful.

GH #58: ``--pose`` additionally bakes a **posed** variant of every skinned
cluster from a shipped first-person ``.xsa`` clip. The pose is the ADR-0441
recipe evaluated offline (``tools/xmd_fk.py``): forward kinematics over the
``NODES`` skeleton from the clip's rotation/movement window slots, then the
influence-weighted skin blend. The canonical pose is the first-person melee
"hands returned to rest" end frame (``FPSMelee.xsa::Mel_ShaUnEquip``, last key);
it is a reproducible, re-bakeable choice, not a validated VR fit.

Usage::

    python tools/xmd_bake.py --cpp src/hook/native_hand_mesh_data.h \
                             --manifest docs/rea/reference/native_hand_mesh.json
    python tools/xmd_bake.py --cpp src/hook/native_hand_mesh_data.h --verify
    python tools/xmd_bake.py --model <file.xmd> --cluster 1 --name Foo --cpp - --json
    python tools/xmd_bake.py --model <file.xmd> --cluster 1 --name Foo --cpp - \
                             --anim <clip.xsa> --sequence Mel_ShaUnEquip --pose-key 17
"""

