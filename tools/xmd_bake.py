#!/usr/bin/env python3
"""Bake real Riddick ``.xmd`` meshes into a native C++ asset (GH #55 -> #46).

``tools/xmd_export.py`` already turns a ``MOS DATAFILE2.0`` ``.xmd`` into OBJ /
skin JSON for inspection. This tool closes the last gap before a native first-
person draw path: it bakes the **bind-pose** geometry of specific clusters into
a dependency-free C++ header (``src/hook/native_hand_mesh_data.h``) that the
hook can compile in directly, so no runtime file I/O or binary re-parser is
needed inside the game process.

It is strictly read-only: the game install is never written, and the emitted
header is the only artifact (plus an optional JSON manifest for evidence).

The canonical bake (``--set hands``) selects the two textured Riddick forearm
clusters from ``Riddick_B05.xmd`` (the in-game body arms, surface
``RIDDICK_ARMSCAR_*``) and both ``Pa2_Hand_01.xmd`` hand clusters:

  * ``Riddick_LeftArm``   Riddick_B05.xmd cluster 1 (526 verts, bones 10-23)
  * ``Riddick_RightArm``  Riddick_B05.xmd cluster 2 (344 verts, bones 10-23)
  * ``Pa2_Hand``          Pa2_Hand_01.xmd cluster 0 (138 verts, textured)
  * ``Pa2_Hand_Detail``   Pa2_Hand_01.xmd cluster 1 (540 verts, untextured)

Coordinate system: the engine's raw model-space floats (Z-up), unconverted.
Skinning caveat: ``.xmd`` stores bind-pose translations only (no rotations
anywhere in the file — ``KEYS`` is a string metadata map, ADR-0421), so the
baked mesh is the artist bind pose; a consumer that poses it must supply the
bone animation from the engine (or the ``.xsa``/``.xag`` groups). The C++ asset
therefore carries the geometry **rigidly** today.

Usage::

    python tools/xmd_bake.py --cpp src/hook/native_hand_mesh_data.h \
                             --manifest docs/rea/reference/native_hand_mesh.json
    python tools/xmd_bake.py --cpp src/hook/native_hand_mesh_data.h --verify
    python tools/xmd_bake.py --model <file.xmd> --cluster 1 --name Foo --cpp - --json
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mos_xmd import GeometryError, Xmd, XmdError  # noqa: E402
import xmd_export  # noqa: E402

DEFAULT_GAME_DIR = r"C:\Program Files (x86)\Starbreeze Studios\Riddick EFBB"
MODELS_SUBDIR = os.path.join("Content", "Models")
GENERATED_BANNER = (
    "AUTO-GENERATED by tools/xmd_bake.py -- do not edit by hand.\n"
    "Regenerate with:\n"
    "  python tools/xmd_bake.py --cpp src/hook/native_hand_mesh_data.h \\\n"
    "                           --manifest docs/rea/reference/native_hand_mesh.json"
)

# Canonical bake set. Paths are relative to <game>/Content/Models so the header
# is reproducible on any machine that owns the same game build (identified by
# the sha256 recorded in the provenance comment).
HAND_SET = [
    ("Characters/Riddick/Riddick_B05.xmd", 1, "Riddick_LeftArm"),
    ("Characters/Riddick/Riddick_B05.xmd", 2, "Riddick_RightArm"),
    ("Characters/Pa2/Pa2_Hand_01.xmd", 0, "Pa2_Hand"),
    ("Characters/Pa2/Pa2_Hand_01.xmd", 1, "Pa2_Hand_Detail"),
]


def _sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _cf(v: float) -> str:
    """Format a float as a compact, deterministic C++ ``float`` literal."""
    if v == 0.0:
        return "0.0f"
    s = f"{v:.6g}"
    if "e" in s or "E" in s:
        return s + "f"
    if "." not in s:
        s += ".0"
    return s + "f"


def bake_mesh(model_path: str, cluster: int, name: str, rel_path: str) -> dict:
    """Decode one cluster into a portable mesh record (no C++ yet)."""
    x = Xmd(model_path)
    mesh = xmd_export.decode_cluster(x, cluster)
    sk = x.skeleton()
    bones = mesh.bones_used()
    infos = x.cluster_infos()
    surface_index = infos[cluster].surface_index if cluster < len(infos) else None
    return {
        "name": name,
        "source": rel_path,
        "source_sha256": _sha256(model_path),
        "source_size": os.path.getsize(model_path),
        "cluster": cluster,
        "surface_index": surface_index,
        "cluster_count": len(xmd_export.vertex_frame_nodes(x)),
        "vertices": mesh.vertex_count,
        "triangles": mesh.tri_count,
        "uvs": len(mesh.uvs) if mesh.uvs is not None else 0,
        "positions": [tuple(p) for p in mesh.positions],
        "normals": [tuple(n) for n in mesh.normals],
        "uv": [tuple(u) for u in mesh.uvs] if mesh.uvs is not None else None,
        "indices": list(mesh.triangles),
        "bounds_min": list(mesh.bounds_min),
        "bounds_max": list(mesh.bounds_max),
        "skinned": mesh.skin is not None,
        "influences": mesh.skin.influence_count if mesh.skin else 0,
        "bone_space": mesh.bone_space,
        "bones_used": bones,
        "skeleton_nodes": len(sk.nodes) if sk else 0,
        "surfaces": x.surface_names(),
    }


def _emit_vertices(out: list[str], ident: str, rec: dict) -> None:
    positions = rec["positions"]
    normals = rec["normals"]
    uv = rec["uv"]
    has_normals = len(normals) == len(positions)
    out.append(f"inline constexpr NativeHandVertex {ident}_Vertices[] = {{")
    for i, p in enumerate(positions):
        n = normals[i] if has_normals else (0.0, 0.0, 1.0)
        u = uv[i] if uv is not None else (0.0, 0.0)
        out.append(
            "    { { %s, %s, %s }, { %s, %s, %s }, { %s, %s } },"
            % (_cf(p[0]), _cf(p[1]), _cf(p[2]),
               _cf(n[0]), _cf(n[1]), _cf(n[2]),
               _cf(u[0]), _cf(u[1])))
    out.append("};")
    out.append("")


def _emit_indices(out: list[str], ident: str, indices: list[int]) -> None:
    out.append(f"inline constexpr unsigned short {ident}_Indices[] = {{")
    row: list[str] = []
    for i, value in enumerate(indices):
        row.append(str(value))
        if len(row) == 12:
            out.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        out.append("    " + ", ".join(row) + ",")
    out.append("};")
    out.append("")


def render_header(records: list[dict]) -> str:
    out: list[str] = []
    out.append("// " + GENERATED_BANNER.replace("\n", "\n// "))
    out.append("//")
    out.append("// Source models (relative to <game>/Content/Models):")
    seen: dict[str, dict] = {}
    for rec in records:
        prev = seen.get(rec["source"])
        if prev is None:
            seen[rec["source"]] = rec
            out.append(f"//   {rec['source']}")
            out.append(f"//     sha256 {rec['source_sha256']}  size {rec['source_size']}")
    out.append("//")
    out.append("// Bind pose only; bone rotations are not stored in .xmd (see")
    out.append("// docs/adr/0420-native-hand-mesh-asset.md).")
    out.append("#pragma once")
    out.append("")
    out.append('#include "native_hand_mesh.h"')
    out.append("")
    out.append("namespace RiddickVR {")
    out.append("namespace NativeHandMeshData {")
    out.append("")
    for i, rec in enumerate(records):
        ident = f"kMesh{i}"
        out.append(f"// {rec['name']}: {rec['source']} cluster {rec['cluster']} "
                   f"({rec['vertices']} verts, {rec['triangles']} tris, "
                   f"{rec['uvs']} uvs, {len(rec['bones_used'])} bones, "
                   f"surface {rec['surface_index']})")
        _emit_vertices(out, ident, rec)
        _emit_indices(out, ident, rec["indices"])
    out.append("inline constexpr NativeHandMesh kMeshes[] = {")
    for i, rec in enumerate(records):
        ident = f"kMesh{i}"
        mn, mx = rec["bounds_min"], rec["bounds_max"]
        surface = rec["surface_index"]
        surface = -1 if surface is None else surface
        out.append(
            '    { "%s", "%s", %d, %d, %s_Vertices, %d, %s_Indices, %d,'
            % (rec["name"], rec["source"].replace("\\", "\\\\"), rec["cluster"],
               surface, ident, rec["vertices"], ident,
               len(rec["indices"])))
        out.append("      { %s, %s, %s }, { %s, %s, %s } },"
                   % (_cf(mn[0]), _cf(mn[1]), _cf(mn[2]),
                      _cf(mx[0]), _cf(mx[1]), _cf(mx[2])))
    out.append("};")
    out.append("")
    out.append("inline constexpr int kMeshCount = "
               "static_cast<int>(sizeof(kMeshes) / sizeof(kMeshes[0]));")
    out.append("")
    out.append("} // namespace NativeHandMeshData")
    out.append("} // namespace RiddickVR")
    out.append("")
    return "\n".join(out)


def render_manifest(records: list[dict], generated_from: str) -> dict:
    def summary(rec: dict) -> dict:
        return {k: rec[k] for k in (
            "name", "source", "source_sha256", "source_size", "cluster",
            "surface_index", "cluster_count", "vertices", "triangles", "uvs",
            "bounds_min", "bounds_max", "skinned", "influences", "bone_space",
            "bones_used", "skeleton_nodes", "surfaces")}

    return {
        "tool": "tools/xmd_bake.py",
        "generated_from": generated_from,
        "coordinate_system": xmd_export.COORDINATE_SYSTEM,
        "rotations_available": False,
        "rotations_note": xmd_export.ROTATIONS_NOTE,
        "meshes": [summary(rec) for rec in records],
        "totals": {
            "meshes": len(records),
            "vertices": sum(rec["vertices"] for rec in records),
            "triangles": sum(rec["triangles"] for rec in records),
        },
    }


def resolve_set(game_dir: str, spec) -> list[dict]:
    records: list[dict] = []
    for rel, cluster, name in spec:
        path = os.path.join(game_dir, MODELS_SUBDIR, rel)
        if not os.path.isfile(path):
            raise XmdError(f"model not found: {path}")
        records.append(bake_mesh(path, cluster, name, rel))
    return records


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game", default=DEFAULT_GAME_DIR,
                    help="game install root (default: %(default)s)")
    ap.add_argument("--model", metavar="FILE",
                    help="bake a single .xmd instead of the canonical set")
    ap.add_argument("--cluster", type=int, action="append", metavar="N",
                    help="cluster index (repeatable; with --model)")
    ap.add_argument("--name", metavar="NAME",
                    help="asset name (single --model/--cluster only)")
    ap.add_argument("--cpp", metavar="FILE",
                    help="write the C++ header here ('-' = stdout)")
    ap.add_argument("--manifest", metavar="FILE",
                    help="write a JSON manifest here")
    ap.add_argument("--verify", action="store_true",
                    help="re-bake and compare against --cpp (no write)")
    ap.add_argument("--json", action="store_true", help="print the manifest")
    args = ap.parse_args(argv)

    try:
        if args.model:
            clusters = args.cluster or [0]
            if len(clusters) > 1:
                ap.error("--name only supports a single --cluster")
            rel = os.path.relpath(os.path.abspath(args.model),
                                  os.path.join(args.game, MODELS_SUBDIR))
            name = args.name or f"{os.path.splitext(os.path.basename(args.model))[0]}_{clusters[0]}"
            records = [bake_mesh(args.model, clusters[0], name, rel)]
            generated_from = "explicit --model"
        else:
            records = resolve_set(args.game, HAND_SET)
            generated_from = f"canonical hand set from {args.game}"

        header = render_header(records)
        manifest = render_manifest(records, generated_from)

        if args.verify:
            if not args.cpp or args.cpp == "-":
                ap.error("--verify needs --cpp FILE")
            if not os.path.isfile(args.cpp):
                print(f"ERROR: {args.cpp} does not exist", file=sys.stderr)
                return 1
            with open(args.cpp, "r", encoding="utf-8", newline="") as f:
                current = f.read()
            current_norm = current.replace("\r\n", "\n")
            if current_norm != header:
                print(f"ERROR: {args.cpp} is stale (re-bake required)",
                      file=sys.stderr)
                return 1
            print(f"OK: {args.cpp} matches a fresh bake "
                  f"({len(records)} meshes, "
                  f"{manifest['totals']['vertices']} verts)")
            return 0

        if args.cpp:
            if args.cpp == "-":
                sys.stdout.write(header)
            else:
                with open(args.cpp, "w", encoding="utf-8", newline="\n") as f:
                    f.write(header)
                print(f"wrote {args.cpp} ({len(records)} meshes, "
                      f"{manifest['totals']['vertices']} verts, "
                      f"{manifest['totals']['triangles']} tris)")
        if args.manifest:
            with open(args.manifest, "w", encoding="utf-8", newline="\n") as f:
                json.dump(manifest, f, indent=2)
                f.write("\n")
            print(f"wrote {args.manifest}")
        if args.json:
            print(json.dumps(manifest, indent=2))
        if not args.cpp and not args.manifest and not args.json:
            ap.error("nothing to do: pass --cpp, --manifest and/or --json")
        return 0
    except (XmdError, GeometryError) as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
